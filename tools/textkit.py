"""한국어 제목·캡션 토큰화 공용 모듈.

`signal_scan.py`(시그널 수집)와 `daily_auto.py`(기사 매칭)가 **같은 토크나이저**를 써야
토큰이 어긋나지 않는다. 다르면 시그널 가점이 조용히 0으로 수렴한다.

의도적으로 표준 라이브러리만 쓴다 — daily_auto는 GitHub Actions에서 돌고,
signal_scan은 로컬 전용(curl_cffi 의존)이라 서로 직접 import하면 안 된다.
"""
import re

# 조사가 붙으면 '덕수궁'과 '덕수궁에서'가 다른 토큰이 된다 → 떼어내고 비교.
_PARTICLE_RE = re.compile(
    r"(에서는|에서도|으로는|이라는|라는|에서|에게|으로|에는|께서|부터|까지|처럼|보다"
    r"|이며|하며|하는|되는|들의|들이|들을|이나|와의|과의|의|은|는|이|가|을|를|도|만|와|과|로)$")

# 아무 글에나 흔해서 겹쳐도 의미 없는 말들
_STOP = {
    "이번", "오늘", "우리", "그리고", "하지만", "지금", "소식", "위해", "합니다",
    "입니다", "있습니다", "했습니다", "여러분", "때문", "대해", "통해", "함께",
    "라는", "가장", "정말", "다양한", "새로운", "특별한", "만나", "소개", "생각",
    "사람", "이야기", "작품", "전시", "예술", "문화", "작가",
}


def normalize(word: str) -> str:
    """말끝 조사 제거."""
    return _PARTICLE_RE.sub("", word)


def topic_key(text: str) -> set:
    """고유명사 위주 토큰 집합.

    길이 임계를 정한 근거(실측):
    - 2글자까지 넣으면 아무 두 글이나 겹쳐서 교차 점수가 무의미해진다 ('교차 27'이 나왔음)
    - 4글자로 올리면 한국어 고유명사 대부분(이대원·덕수궁·회고전)이 빠진다
    → 3글자 + 조사 제거 + 불용어 제외.
    """
    tokens = set(re.findall(r"@([A-Za-z0-9_.]{4,})", text))       # 계정 멘션
    tokens |= set(re.findall(r"\b([A-Z][A-Za-z]{3,})\b", text))   # 영문 고유명사
    for w in re.findall(r"[가-힣]{3,}", text):
        w = normalize(w)
        if len(w) >= 3 and w not in _STOP:
            tokens.add(w)
    return tokens
